#!/usr/bin/env python3
"""Refresh Arduino build adapters after replacing the SquareLine ui/ export.

Uses only Python's standard library. Does not write to the ui/ directory.
Existing application code in ui_events.c must be merged by the user as usual.
"""
from pathlib import Path
import os
import re
import shutil


def refresh(project: Path) -> None:
    ui = project / "ui"
    if not (ui / "ui.h").is_file() or not (ui / "ui.c").is_file():
        raise ValueError("Place the SquareLine export directly in ui/ first.")
    sources = sorted(ui.rglob("*.c"))
    text = "\n".join(f.read_text(encoding="utf-8-sig")
                     for f in ui.rglob("*") if f.suffix in (".c", ".h"))
    fonts = sorted({int(size) for size in
                    re.findall(r"\blv_font_montserrat_(\d+)\b", text)})
    invalid = [size for size in fonts if size < 8 or size > 48 or size % 2]
    if invalid:
        raise ValueError(f"Unsupported built-in Montserrat size(s): {invalid}")

    # This supplied export declares the same custom alias in two screens.
    # Rename the StorageManager alias during preprocessing, leaving both
    # original .c/.h files untouched. It is a no-op after fixing the name in SLS.
    storage_header = ui / "screens/ui_ScreenStorageManager.h"
    storage_source = Path("screens/ui_ScreenStorageManager.c")
    alias_fix = (storage_header.is_file() and
                 re.search(r"\buic_Update\b", storage_header.read_text()))

    api = ["// Generated by tools/update_ui_build.py. Do not edit.",
           "#pragma once", '#include "lvgl/lvgl.h"']
    if alias_fix:
        # Load the affected header with its alias BEFORE ui.h includes it.
        api += ["#define uic_Update uic_ScreenStorageManager",
                '#include "../ui/screens/ui_ScreenStorageManager.h"',
                "#undef uic_Update"]
    api += ['#include "../ui/ui.h"', ""]
    (project / "src/squareline_api.h").write_text("\n".join(api))

    wrappers = project / "src/squareline_build"
    if wrappers.exists():
        shutil.rmtree(wrappers)  # Only machine-generated wrappers, never ui/.
    for source in sources:
        rel = source.relative_to(ui)
        wrapper = wrappers / rel
        wrapper.parent.mkdir(parents=True, exist_ok=True)
        relative = lambda path: Path(os.path.relpath(path, wrapper.parent)).as_posix()
        lines = ["// Generated build adapter; the SquareLine source is unchanged.",
                 f'#include "{relative(project / "src/squareline_api.h")}"']
        if alias_fix and rel == storage_source:
            lines += ["#define uic_Update uic_ScreenStorageManager"]
        lines += [f'#include "{relative(source)}"']
        if alias_fix and rel == storage_source:
            lines += ["#undef uic_Update"]
        wrapper.write_text("\n".join(lines) + "\n")

    header = ["// Generated from the built-in fonts referenced by ui/.", "#pragma once"]
    for size in fonts:
        header += [f"#undef LV_FONT_MONTSERRAT_{size}",
                   f"#define LV_FONT_MONTSERRAT_{size} 1"]
    (project / "src/squareline_fonts.h").write_text("\n".join(header) + "\n")
    print(f"Build adapters refreshed: {len(sources)} C sources; Montserrat {fonts}.")
    print("ui/ was not modified. Merge your ui_events.c changes, then build in Arduino IDE.")


if __name__ == "__main__":
    refresh(Path(__file__).resolve().parents[1])
